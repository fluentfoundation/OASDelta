#!/usr/bin/env python3
"""Generates C# tables (rule ids, rule registry, localizations) from the upstream Go checker sources."""
import json, re, sys, os, glob
SRC = sys.argv[1]          # .../oasdiff/checker
OUT = sys.argv[2]          # .../src/OasDelta/Checker/Generated
os.makedirs(OUT, exist_ok=True)

def go_str(s):
    # Go interpreted string literal -> python str (json-compatible escapes)
    return json.loads(s)

# ---------------------------------------------------------------- ids
ids = {}
for f in sorted(glob.glob(os.path.join(SRC, '*.go'))):
    if f.endswith('_test.go'): continue
    txt = open(f).read()
    for m in re.finditer(r'^\s*([A-Z][A-Za-z0-9]*Id)\s*=\s*("(?:[^"\\]|\\.)*")', txt, re.M):
        ids[m.group(1)] = go_str(m.group(2))
with open(os.path.join(OUT, 'RuleIds.g.cs'), 'w') as o:
    o.write('// <auto-generated>Generated from upstream oasdiff checker sources by tools/gen_checker_tables.py</auto-generated>\n')
    o.write('namespace OasDelta.Checker;\n\npublic static partial class Ids\n{\n')
    for k in sorted(ids):
        o.write(f'    public const string {k[:-2]} = {json.dumps(ids[k])};\n')
    o.write('}\n')

# ---------------------------------------------------------------- rules
rtxt = open(os.path.join(SRC, 'rules.go')).read()
body = rtxt[rtxt.index('func handWrittenRules()'):]
body = body[:body.index('\n}\n')]
rules = []
for m in re.finditer(r'newBackwardCompatibilityRule\((.*?)\),?\s*$', body, re.M):
    args = m.group(1)
    # split top-level commas (respecting [] {} and quotes)
    parts, depth, cur, q = [], 0, '', False
    for ch in args:
        if ch == '"' : q = not q
        if not q and ch in '[{(': depth += 1
        if not q and ch in ']})': depth -= 1
        if ch == ',' and depth == 0 and not q:
            parts.append(cur.strip()); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur.strip())
    rid, level, handler, direction, area, kind, effect, guards = parts[:8]
    locs = [go_str(p) for p in parts[8:]]
    g = re.findall(r'Guard[A-Za-z]+', guards) if guards != 'nil' else []
    rules.append((rid, level, handler, direction, area, kind, effect, g, locs))

def cs_id(x): return 'Ids.' + x[:-2]
with open(os.path.join(OUT, 'RuleTable.g.cs'), 'w') as o:
    o.write('// <auto-generated>Generated from upstream oasdiff checker/rules.go by tools/gen_checker_tables.py</auto-generated>\n')
    o.write('namespace OasDelta.Checker;\n\npublic static partial class Rules\n{\n')
    o.write('    private static List<Rule> HandWritten() =>\n    [\n')
    for rid, level, handler, direction, area, kind, effect, g, locs in rules:
        h = 'null' if handler == 'nil' else f'Checks.{handler}'
        gs = '[' + ', '.join('Guard.' + x[5:] for x in g) + ']'
        ls = '[' + ', '.join(json.dumps(x) for x in locs) + ']'
        o.write(f'        new({cs_id(rid)}, Level.{level}, {h}, Direction.{direction[9:]}, Area.{area[4:]}, Kind.{kind[4:]}, Effect.{effect[6:]}, {gs}, {ls}),\n')
    o.write('    ];\n}\n')
handlers = sorted(set(r[2] for r in rules if r[2] != 'nil'))
with open(os.path.join(OUT, 'handlers.txt'), 'w') as o:
    o.write('\n'.join(handlers) + '\n')

# ---------------------------------------------------------------- localizations
ltxt = open(os.path.join(SRC, 'localizations', 'localizations.go')).read()
langs = {}
for m in re.finditer(r'^\s*"([a-z\-]+)\.messages\.([^"]+)":\s*("(?:[^"\\]|\\.)*"),\s*$', ltxt, re.M):
    langs.setdefault(m.group(1), {})[m.group(2)] = go_str(m.group(3))
with open(os.path.join(OUT, 'Localizations.g.cs'), 'w') as o:
    o.write('// <auto-generated>Generated from upstream oasdiff checker/localizations by tools/gen_checker_tables.py</auto-generated>\n')
    o.write('namespace OasDelta.Checker;\n\npublic static partial class Localizations\n{\n')
    for lang in sorted(langs):
        name = 'L_' + lang.replace('-', '_')
        o.write(f'    private static Dictionary<string, string> {name}() => new(StringComparer.Ordinal)\n    {{\n')
        for k in sorted(langs[lang]):
            o.write(f'        [{json.dumps(k)}] = {json.dumps(langs[lang][k], ensure_ascii=False)},\n')
        o.write('    };\n')
    o.write('    private static Dictionary<string, string> ForLang(string lang) => lang switch\n    {\n')
    for lang in sorted(langs):
        o.write(f'        {json.dumps(lang)} => L_{lang.replace("-", "_")}(),\n')
    o.write('        _ => L_en(),\n    };\n')
    o.write('    public static readonly string[] Languages = [' + ', '.join(json.dumps(l) for l in sorted(langs)) + '];\n')
    o.write('}\n')
print(f'ids={len(ids)} rules={len(rules)} handlers={len(handlers)} langs={ {k: len(v) for k, v in langs.items()} }')
