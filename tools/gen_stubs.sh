#!/bin/bash
# Emits stubs for check handlers referenced by the rule table but not yet implemented.
D=$(cd "$(dirname "$0")/../src/OasDelta/Checker" && pwd)
OUT=$D/Generated/Stubs.g.cs
{
echo "// <auto-generated>Stubs for unported checks</auto-generated>"
echo "namespace OasDelta.Checker;"
echo "public static partial class Checks"
echo "{"
for h in $(cat $D/Generated/handlers.txt); do
  if ! grep -rqs --include=*.cs --exclude=Stubs.g.cs "public static List<Change> $h(" $D; then
    echo "    public static List<Change> $h(OasDelta.Diff.OpenApiDiff d, Sources s, CheckerConfig c) => [];"
  fi
done
echo "}"
} > $OUT
grep -c "=> \[\];" $OUT
