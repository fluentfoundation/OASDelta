#!/usr/bin/env python3
"""Lists the fixture pairs that upstream oasdiff's own checker tests compare, so the goldens cover them too.

usage: mine_upstream_pairs.py OASDIFF_SOURCE_DIR > tests/extra-pairs.txt

Within each Go test function, consecutive open("../data/...") calls are read as (base, revision) pairs. Pairs whose
files are missing from tests/fixtures, and pairs tools/pairs.sh already produces by naming convention, are left out.
Reversed pairs (revision -> base) are kept: they are how the tests reach the "removed" rules.
"""
import os
import re
import subprocess
import sys

sys.stdout.reconfigure(newline="\n")  # LF on every OS
src, root = sys.argv[1], os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fixtures = os.path.join(root, "tests", "fixtures")
pairs = []
for name in sorted(os.listdir(os.path.join(src, "checker"))):
    if not name.endswith("_test.go"):
        continue
    with open(os.path.join(src, "checker", name), encoding="utf-8") as f:
        for fn in re.split(r"\nfunc Test", f.read()):
            opened = re.findall(r'open\("\.\./data/([^"]+)"\)', fn)
            for a, b in zip(opened[0::2], opened[1::2]):
                if a != b and (a, b) not in pairs:
                    pairs.append((a, b))

env = dict(os.environ, PAIRS_SKIP_EXTRA="1")
have = set()
for line in subprocess.run(["bash", os.path.join(root, "tools", "pairs.sh")], capture_output=True, text=True, env=env).stdout.splitlines():
    if line.strip():
        b, r = line.split()
        have.add((b.removeprefix("./"), r.removeprefix("./")))

print("# Fixture pairs compared by upstream oasdiff's checker tests that tools/pairs.sh does not produce by naming")
print("# convention. Generated by tools/mine_upstream_pairs.py; one '<base> <revision>' per line, relative to tests/fixtures.")
for a, b in pairs:
    if (a, b) not in have and all(os.path.exists(os.path.join(fixtures, x)) for x in (a, b)):
        print(f"./{a} ./{b}")
